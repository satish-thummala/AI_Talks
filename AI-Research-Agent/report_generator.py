
from datetime import datetime
from pathlib import Path


def generate_report(research_result, output_file="research_report.md"):
    """
    Save AI research results as a Markdown report.
    """

    query = research_result.get("query", "Untitled Research")
    analysis = research_result.get("analysis", "")
    sources = research_result.get("sources", [])

    report_date = datetime.now().astimezone().strftime(
        "%Y-%m-%d %H:%M %Z"
    )

    lines = [
        f"# AI Research Report: {query}",
        "",
        f"**Research date:** {report_date}",
        "",
        "## Research Question",
        "",
        query,
        "",
        "## Research Analysis",
        "",
        analysis,
        "",
        "## Sources",
        ""
    ]

    if sources:
        for index, source in enumerate(sources, start=1):
            title = source.get("title") or f"Source {index}"
            url = source.get("url", "")

            # Escape characters that could break Markdown links.
            safe_title = title.replace("[", "\\[").replace("]", "\\]")

            if url:
                lines.append(
                    f"{index}. [{safe_title}]({url})"
                )
            else:
                lines.append(f"{index}. {safe_title}")
    else:
        lines.append("No sources were collected.")

    lines.extend([
        "",
        "---",
        "",
        "*Generated by the Python AI Research Agent.*",
        ""
    ])

    report_content = "\n".join(lines)

    output_path = Path(output_file)
    output_path.write_text(report_content, encoding="utf-8")

    return output_path.resolve()


